/**
 * Mafqoudat's push service worker.
 *
 * The only reason this file exists: a browser will not deliver a push
 * notification to a page, only to a service worker, and it runs this one even
 * when every tab of the site is closed - which is the whole point of the
 * channel. Someone who found a wallet three weeks ago has no reason to have
 * Mafqoudat open today, and they are exactly who a match alert has to reach.
 *
 * Deliberately NOT a full offline/caching worker. This app is not a PWA and
 * has never cached its own assets; a worker that started intercepting `fetch`
 * would quietly become the thing that decides what version of the site a
 * visitor sees, which is a far larger commitment than receiving a notification.
 * So there is no `fetch` handler here at all, and the file is served from
 * `public/` untouched by the build rather than generated by Workbox.
 *
 * Payloads are written by server/services/webPushService.js and are always
 * `{ title, body, data }`.
 */

// Take over as soon as it is installed, rather than waiting for every tab of
// the site to close: a visitor who has just granted permission from a page
// they are still looking at should be subscribed by that page's own worker.
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (event) => event.waitUntil(self.clients.claim()));

const FALLBACK_TITLE = 'Mafqoudat';
const ICON = '/icon-192.png';
const BADGE = '/favicon-96.png';

const readPayload = (event) => {
  if (!event.data) return {};
  try {
    return event.data.json();
  } catch (error) {
    // A payload that is not JSON is not something this app sent, but showing
    // the raw text is still better than showing nothing: the browser requires
    // a notification for every push it delivers (userVisibleOnly), and one
    // that never appears is what gets a site's permission revoked.
    return { body: event.data.text() };
  }
};

self.addEventListener('push', (event) => {
  const payload = readPayload(event);
  const data = payload.data || {};

  event.waitUntil(
    self.registration.showNotification(payload.title || FALLBACK_TITLE, {
      body: payload.body || '',
      icon: ICON,
      badge: BADGE,
      data,
      // One notification per listing per kind, rather than a stack of them:
      // re-scoring a pair or a second alert about the same post replaces what
      // is on screen instead of adding to it.
      tag: data.type && data.postId ? `${data.type}:${data.postId}` : undefined,
      // Arabic and French copy arrive as-is; the direction is the reader's,
      // and 'auto' is what lets the browser take it from the text itself
      // rather than from this file's own locale.
      dir: 'auto',
    })
  );
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();

  const target = event.notification.data?.url;
  if (!target) return;

  // Reuse a tab that is already on this site rather than opening a second one,
  // and navigate it - a visitor with the dashboard open should find themselves
  // on the listing, not with two windows of the same app.
  event.waitUntil(
    self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then((clientList) => {
      for (const client of clientList) {
        if (client.url === target && 'focus' in client) return client.focus();
      }

      const sameOrigin = clientList.find((client) => {
        try {
          return new URL(client.url).origin === new URL(target).origin;
        } catch (error) {
          return false;
        }
      });

      if (sameOrigin && 'navigate' in sameOrigin) {
        return sameOrigin.navigate(target).then((client) => client && client.focus());
      }
      return self.clients.openWindow(target);
    })
  );
});
