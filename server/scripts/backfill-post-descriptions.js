/**
 * Backfill Script: Populate Missing Post Descriptions
 *
 * Scans all posts in the database that currently lack a description (or have
 * an empty/whitespace description) and generates a natural, SEO-optimized
 * description using `descriptionGenerator.js`.
 *
 * Safety features:
 * - Never overwrites custom user-authored descriptions.
 * - Defaults to DRY-RUN mode (pass --apply to execute changes).
 * - Rotates through template styles (variationIndex) to maintain content variety.
 * - Cleans and invalidates post cache upon successful execution.
 *
 * Usage:
 *   Dry Run (preview only):
 *     node server/scripts/backfill-post-descriptions.js
 *
 *   Apply Changes:
 *     node server/scripts/backfill-post-descriptions.js --apply
 *
 *   Optional flags:
 *     --force      Also re-generate descriptions for posts already flagged as isAutoGeneratedDescription
 *     --limit=N    Process at most N posts (e.g. --limit=50)
 *     --lang=ar    Specify generation language ('ar', 'fr', 'en', default: 'ar')
 *     --verbose    Print details for every single post processed
 */

require('dotenv').config();
const mongoose = require('mongoose');
const Post = require('../models/Post');
const Country = require('../models/Country');
const Category = require('../models/Category');
const FoundLost = require('../models/FoundLost');
const City = require('../models/City');
const { generatePostDescription, isAutoGeneratedDescription } = require('../utils/descriptionGenerator');

// CLI Arguments
const args = process.argv.slice(2);
const APPLY = args.includes('--apply');
const FORCE = args.includes('--force');
const VERBOSE = args.includes('--verbose');

const limitArg = args.find((a) => a.startsWith('--limit='));
const LIMIT = limitArg ? parseInt(limitArg.split('=')[1], 10) : 0;

const langArg = args.find((a) => a.startsWith('--lang='));
const LANGUAGE = (langArg ? langArg.split('=')[1] : 'ar').toLowerCase();

async function backfillPostDescriptions() {
  const startTime = Date.now();
  console.log('='.repeat(70));
  console.log('🚀 BACKFILL SCRIPT: AUTO-GENERATE DESCRIPTIONS FOR EXISTING POSTS');
  console.log('='.repeat(70));
  console.log(`Mode:      ${APPLY ? '⚡ APPLY (writing changes to DB)' : '🔍 DRY RUN (simulation only)'}`);
  console.log(`Language:  ${LANGUAGE}`);
  console.log(`Force:     ${FORCE ? 'Yes (re-evaluating auto-generated descriptions)' : 'No (empty/missing only)'}`);
  if (LIMIT > 0) console.log(`Limit:     ${LIMIT} posts`);
  console.log('-'.repeat(70));

  try {
    const mongoUri = process.env.MONGODB_URI || 'mongodb://localhost:27017/mafqoudat';
    console.log('🔗 Connecting to database...');
    await mongoose.connect(mongoUri);
    console.log('✅ Connected to MongoDB successfully.\n');

    // Build query filter
    const emptyDescFilter = [
      { description: { $exists: false } },
      { description: null },
      { description: '' },
      { description: /^\s*$/ },
    ];

    const queryFilter = FORCE
      ? { $or: [...emptyDescFilter, { isAutoGeneratedDescription: true }] }
      : { $or: emptyDescFilter };

    const totalTargetCount = await Post.countDocuments(queryFilter);
    console.log(`📊 Found ${totalTargetCount} post(s) needing description generation.`);

    if (totalTargetCount === 0) {
      console.log('🎉 All posts already have valid descriptions. Nothing to backfill!');
      await mongoose.disconnect();
      return;
    }

    let query = Post.find(queryFilter)
      .populate('country', 'code names labels')
      .populate('categories', 'code labels')
      .populate('category', 'code labels')
      .populate('foundLost', 'code labels');

    if (LIMIT > 0) {
      query = query.limit(LIMIT);
    }

    const posts = await query.exec();
    console.log(`🔎 Loaded ${posts.length} post(s) for processing...\n`);

    // Cache pre-fetched city records to avoid repetitive DB lookups
    const cityCache = new Map();
    const cityIdsToFetch = [
      ...new Set(
        posts
          .map((p) => p.city)
          .filter((c) => c && mongoose.Types.ObjectId.isValid(c))
          .map((c) => c.toString())
      ),
    ];

    if (cityIdsToFetch.length > 0) {
      const cityDocs = await City.find({ _id: { $in: cityIdsToFetch } }).select('code labels').lean();
      for (const cityDoc of cityDocs) {
        cityCache.set(cityDoc._id.toString(), cityDoc);
      }
    }

    const updates = [];
    const previewSamples = [];

    for (let i = 0; i < posts.length; i++) {
      const post = posts[i];

      // Country Name
      const countryDoc = post.country;
      const countryName = countryDoc
        ? (countryDoc.names?.[LANGUAGE] || countryDoc.labels?.[LANGUAGE] || countryDoc.names?.ar || countryDoc.code || '')
        : '';

      // Category Names
      let categoryDocs = post.categories && post.categories.length > 0 ? post.categories : [];
      if (categoryDocs.length === 0 && post.category) {
        categoryDocs = [post.category];
      }
      const categoryNames = categoryDocs
        .map((cat) => cat.labels?.[LANGUAGE] || cat.labels?.ar || cat.code)
        .filter(Boolean);

      // Direction (LOST / FOUND)
      const direction = post.foundLost?.code === 'FOUND' ? 'FOUND' : 'LOST';

      // City Name
      let cityName = '';
      if (post.city) {
        const cityIdStr = post.city.toString();
        if (cityCache.has(cityIdStr)) {
          const cityDoc = cityCache.get(cityIdStr);
          cityName = cityDoc.labels?.[LANGUAGE] || cityDoc.labels?.ar || cityDoc.code || '';
        } else if (typeof post.city === 'string' && !post.city.startsWith('api_')) {
          cityName = post.city;
        }
      }

      // Exact Location & Date
      const exactLocation = post.exactLocation || '';
      const date = post.mainDate || '';

      // Rotate template styles across posts for SEO variation
      const variationIndex = i % 3;

      const generatedDescription = generatePostDescription({
        direction,
        categoryNames,
        countryName,
        cityName,
        exactLocation,
        date,
        language: LANGUAGE,
        variationIndex,
      });

      updates.push({
        updateOne: {
          filter: { _id: post._id },
          update: {
            $set: {
              description: generatedDescription,
              isAutoGeneratedDescription: true,
            },
          },
        },
      });

      if (previewSamples.length < 5 || VERBOSE) {
        previewSamples.push({
          id: post._id.toString(),
          type: direction,
          categories: categoryNames.join(', ') || 'غرض',
          city: cityName || 'N/A',
          generated: generatedDescription,
        });
      }
    }

    // Display sample preview
    console.log('📝 SAMPLE PREVIEWS OF GENERATED DESCRIPTIONS:');
    console.log('-'.repeat(70));
    previewSamples.forEach((sample, idx) => {
      console.log(`[${idx + 1}] Post ID: ${sample.id} (${sample.type} - ${sample.categories})`);
      console.log(`    City:        ${sample.city}`);
      console.log(`    Description: "${sample.generated}"\n`);
    });

    if (!APPLY) {
      console.log('='.repeat(70));
      console.log('ℹ️  DRY RUN COMPLETED.');
      console.log(`   ${updates.length} post(s) would be updated with dynamic descriptions.`);
      console.log('   To apply these changes permanently to the database, run:');
      console.log('   👉 node server/scripts/backfill-post-descriptions.js --apply\n');
      console.log('='.repeat(70));
    } else {
      console.log(`✏️  Applying updates to ${updates.length} post(s)...`);
      const bulkResult = await Post.bulkWrite(updates);

      console.log('\n📈 BACKFILL EXECUTION SUMMARY:');
      console.log('-'.repeat(70));
      console.log(`✅ Matched posts:  ${bulkResult.matchedCount || updates.length}`);
      console.log(`✅ Modified posts: ${bulkResult.modifiedCount || 0}`);
      console.log(`⏱️  Duration:       ${((Date.now() - startTime) / 1000).toFixed(2)}s`);

      // Invalidate relevant cache keys
      console.log('\n🧹 Clearing cache for posts & dashboard...');
      try {
        const { cacheService } = require('../config/cache');
        if (cacheService && cacheService.invalidatePattern) {
          await cacheService.invalidatePattern('posts:*');
          await cacheService.invalidatePattern('dashboard:*');
          console.log('✅ Cache invalidated.');
        }
      } catch (cacheErr) {
        console.warn('⚠️  Could not invalidate cache (non-critical):', cacheErr.message);
      }

      console.log('\n🎉 Backfill successfully completed!');
      console.log('='.repeat(70));
    }

    await mongoose.disconnect();
    console.log('🔌 Disconnected from MongoDB.');
  } catch (error) {
    console.error('\n❌ Error during backfill:', error);
    try {
      await mongoose.disconnect();
    } catch (_) {}
    process.exit(1);
  }
}

backfillPostDescriptions();
